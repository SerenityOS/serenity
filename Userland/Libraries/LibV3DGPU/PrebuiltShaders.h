// Because we don't have our own shader compiler (yet), these shaders are precompiled by Mesa (version 26.2.7-1~bpo13+0~rpt1).
// These prebuilt shaders require certain uniforms, which are generated by the generate_uniforms() function.

// Source vertex shader:
//   #version 300 es
//
//   layout(location = 0) in vec4 a_position;
//   layout(location = 1) in vec4 a_color;
//   layout(location = 2) in vec2 a_texture_coordinate;
//
//   uniform mat4 u_model_view_projection;
//
//   out vec4 v_color;
//   out vec2 v_texture_coordinate;
//
//   void main() {
//       gl_Position = u_model_view_projection * a_position;
//       v_color = a_color;
//       v_texture_coordinate = a_texture_coordinate;
//   }

// Source fragment shader:
//   #version 300 es
//   precision highp float;
//
//   in vec4 v_color;
//   in vec2 v_texture_coordinate;
//
//   out vec4 f_color;
//
//   uniform uint u_alpha_test_function;
//   uniform float u_alpha_test_reference;
//
//   uniform uint u_texture_env_mode;
//   uniform vec4 u_texture_env_color;
//
//   uniform sampler2D sampler;
//
//   bool alpha_test() {
//       switch (u_alpha_test_function) {
//       case 0u: // Never
//           return false;
//       case 1u: // Always
//           return true;
//       case 2u: // Less
//           return f_color.a < u_alpha_test_reference;
//       case 3u: // LessOrEqual
//           return f_color.a <= u_alpha_test_reference;
//       case 4u: // Equal
//           return f_color.a == u_alpha_test_reference;
//       case 5u: // NotEqual
//           return f_color.a != u_alpha_test_reference;
//       case 6u: // GreaterOrEqual
//           return f_color.a >= u_alpha_test_reference;
//       case 7u: // Greater
//           return f_color.a > u_alpha_test_reference;
//       }
//   }
//
//   vec4 texture_function(vec4 current_color, vec4 texel) {
//       switch (u_texture_env_mode) {
//       case 0u: // Add
//           return current_color + texel;
//       case 1u: // Blend
//           return vec4(mix(current_color.rgb, u_texture_env_color.rgb, texel.rgb), current_color.a * texel.a);
//       case 2u: // Combine
//           return vec4(1, 0, 1, 1); // FIXME
//       case 3u: // Decal
//           return vec4(mix(current_color.rgb, texel.rgb, texel.a), current_color.a);
//       case 4u: // Modulate
//           return current_color * texel;
//       case 5u: // Replace
//           return texel;
//       }
//   }
//
//   void main() {
//       f_color = texture_function(v_color, texture(sampler, v_texture_coordinate));
//
//       if (!alpha_test())
//           discard;
//   }

